 assert.equal(tipSet.pages[0].elements[0].tooltipPreview.lines.flat().map(r=>r.text).join(''),'姓名=<$STR(S0)>/$STM(HP) 血量=123 滑块=25');
 assert.equal(tipSet.pages[0].elements[0].tooltipPreview.raw,tip.raw,'tooltip source must stay unchanged');
 const onlyTip='[@main]\n#SAY\n<Img|wil=NewopUI|pcimg=12|x=20|y=20|tips={姓名=$STM(USERNAME)/FCOLOR=250} 血量=$STM(HP)|tipsx=8|tipsy=9>';
