 const menuSource=source+'\n<MenuItem|menuid=S0|x=60|y=200|width=240|height=30|itemname=姓名=$STM(USERNAME)#血量=$STM(HP)#滑块=$STM(SLIDERV_N0)|select=姓名=$STM(USERNAME)|itemhei=30>';
