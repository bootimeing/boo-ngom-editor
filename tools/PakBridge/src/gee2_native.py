def _rol(value, bits):
    return ((value << bits) | (value >> (32 - bits))) & 0xFFFFFFFF


def _perm(a, b, shift, mask):
    temporary = ((a >> shift) ^ b) & mask
    return (a ^ (temporary << shift)) & 0xFFFFFFFF, (b ^ temporary) & 0xFFFFFFFF


def des_schedule_block(block, schedule, *, decrypt=False, permutation_mask=0x33333333):
    """Transform one 8-byte block with a DCP 32-word round schedule."""
    if len(block) != 8 or len(schedule) != 32:
        raise ValueError('DES block/schedule must contain 8 bytes/32 words')
    r, l = struct.unpack('<II', block)
    l, r = _perm(l, r, 4, 0x0F0F0F0F)
    r, l = _perm(r, l, 16, 0x0000FFFF)
    l, r = _perm(l, r, 2, permutation_mask)
    r, l = _perm(r, l, 8, 0x00FF00FF)
    l, r = _perm(l, r, 1, 0x55555555)
    r, l = _rol(r, 3), _rol(l, 3)
    for i in (range(30, -1, -2) if decrypt else range(0, 32, 2)):
        u = r ^ schedule[i]
        t = _rol(r ^ schedule[i + 1], 28)
        f = 0
        for pair in range(4):
            shift = 2 + pair * 8
            f ^= _SP[pair * 2][(u >> shift) & 63]
            f ^= _SP[pair * 2 + 1][(t >> shift) & 63]
        l, r = r, l ^ f
    # After the even number of rounds the halves match DCP's unrolled loop.
    r, l = _rol(r, 29), _rol(l, 29)
    r, l = _perm(r, l, 1, 0x55555555)
    l, r = _perm(l, r, 8, 0x00FF00FF)
    r, l = _perm(r, l, 2, permutation_mask)
    l, r = _perm(l, r, 16, 0x0000FFFF)
    r, l = _perm(r, l, 4, 0x0F0F0F0F)
    return struct.pack('<II', l, r)


def image_header_secondary(schedule_bytes, seed20):
    if len(schedule_bytes) != 128 or len(seed20) != 20:
        raise ValueError('GEE2 material must contain 128-byte schedule and 20-byte seed')
    schedule = list(struct.unpack('<32I', schedule_bytes))
    for i in range(0, 32, 2):
        schedule[i] ^= schedule[i + 1]
    return des_schedule_block(seed20[:8], schedule)


def decrypt_global_header(encrypted, schedule_bytes, seed20):
    if len(encrypted) != 256 or len(schedule_bytes) != 128 or len(seed20) != 20:
        raise ValueError('GEE2 global header/material sizes must be 256/128/20 bytes')
    schedule = struct.unpack('<32I', schedule_bytes)
    feedback = seed20
    result = bytearray()
    for offset in range(0, 240, 20):
        block = encrypted[offset:offset + 20]
        stage = des_schedule_block(block[:8], schedule, decrypt=True, permutation_mask=0x33333331) + block[8:]
        result.extend(a ^ b for a, b in zip(stage, feedback))
        feedback = block
    tail_stream = des_schedule_block(feedback[:8], schedule, permutation_mask=0x33333331) + feedback[8:]
    result.extend(a ^ b for a, b in zip(encrypted[240:], tail_stream))
    return bytes(result)
